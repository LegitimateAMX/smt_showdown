function skillEntriesInCategoryOrder(categories) {
  return categories.flatMap((category) => [
    ...Object.entries(category.skills || {}),
    ...skillEntriesInCategoryOrder(category.subcategories || []),
  ]);
}

const categorizedSkillEntries = skillEntriesInCategoryOrder(NOCTURNE_SKILL_CATEGORIES);
const categorizedSkillIds = categorizedSkillEntries.map(([id]) => id);
const duplicateSkillIds = [...new Set(categorizedSkillIds.filter(
  (id, index) => categorizedSkillIds.indexOf(id) !== index,
))];

if (duplicateSkillIds.length) {
  throw new Error(`Nocturne skills must appear in exactly one category: ${duplicateSkillIds.join(', ')}`);
}

/** Flat lookup consumed by demons and the battle engine. */
export const NOCTURNE_SKILLS = Object.fromEntries(categorizedSkillEntries);
